import { DENSITY_SCALE, SLOTS, type SlotDefinition } from "./slots";
import { ASSET_ID, parseFamilyName } from "./validate";
import { defaultThemeValues, type ThemeValues } from "./values";

// Writes a theme as CSS custom properties (plan.md §9.1, step 4). Every value has already passed
// the grammar in validate.ts, and font faces are rebuilt from checked parts here, so nothing in
// the output comes from a token file verbatim.
//
// The same emitter writes the bundled defaults (app/theme-defaults.css) and every imported theme
// served at /theme.css, so the variable names can't drift between the two.

export interface FontFace {
  assetId: string;
  family: string;
  weight: number;
  style: "normal" | "italic";
}

const cssSlots = SLOTS.filter((s): s is SlotDefinition & { cssVar: string } => s.cssVar !== null);

function fontFaceCss(font: FontFace): string | null {
  const family = parseFamilyName(font.family);
  if (!family || !ASSET_ID.test(font.assetId)) return null;
  if (!Number.isInteger(font.weight) || font.weight < 1 || font.weight > 1000) return null;
  const style = font.style === "italic" ? "italic" : "normal";
  return [
    "@font-face {",
    `  font-family: "${family}";`,
    `  src: url("/api/brand-assets/${font.assetId}") format("woff2");`,
    `  font-weight: ${font.weight};`,
    `  font-style: ${style};`,
    "  font-display: swap;",
    "}",
    "",
  ].join("\n");
}

export function emitThemeCss(
  values: ThemeValues,
  fonts: FontFace[] = [],
  header = "/* OfficeOrg theme. Generated by the Branding admin page. */",
): string {
  const density = values.light.density as keyof typeof DENSITY_SCALE;
  const scale = DENSITY_SCALE[density] ?? 1;

  const light = cssSlots.map((s) => `  ${s.cssVar}: ${values.light[s.name]};`);
  light.push(`  --theme-spacing: calc(var(--theme-spacing-base) * ${scale});`);

  const out = [header, ""];
  for (const font of fonts) {
    const css = fontFaceCss(font);
    if (css) out.push(css);
  }
  out.push(
    ":root {",
    `  color-scheme: ${values.dark ? "light dark" : "light"};`,
    ...light,
    "}",
    "",
  );

  if (values.dark) {
    const dark = values.dark;
    const changed = cssSlots
      .filter((s) => dark[s.name] !== values.light[s.name])
      .map((s) => `    ${s.cssVar}: ${dark[s.name]};`);
    if (changed.length > 0)
      out.push("@media (prefers-color-scheme: dark) {", "  :root {", ...changed, "  }", "}", "");
  }
  return out.join("\n");
}

// The CSS for the default theme, bundled with globals.css as the fallback under /theme.css.
export function defaultThemeCss(): string {
  return emitThemeCss(
    defaultThemeValues(),
    [],
    "/* Generated from packages/core/theme/slots.ts by `pnpm theme:defaults`. Do not edit. */",
  );
}
